import re
from collections import Counter
from pathlib import Path

from django.conf import settings
from django.contrib.auth import get_user_model
from django.core.management.base import BaseCommand, CommandError
from django.test import Client
from django.urls import reverse

REPORT_PATH = Path(settings.BASE_DIR) / "docs" / "profiling" / "silk_report.md"


class Command(BaseCommand):
    help = (
        "Hit the summary endpoint before and after the fix through the full "
        "middleware stack, then write django-silk's recorded numbers to "
        "docs/profiling/silk_report.md."
    )

    def add_arguments(self, parser):
        parser.add_argument("--username", default="demo")

    def handle(self, *args, **opts):
        if not settings.ENABLE_SILK:
            raise CommandError("Silk is disabled; run with ENABLE_SILK=1.")
        from silk.models import Request

        user = get_user_model().objects.filter(username=opts["username"]).first()
        if user is None:
            raise CommandError("Run `manage.py seed_orders` first.")

        client = Client()
        client.force_login(user)

        rows = []
        for label, name in [
            ("Before fix", "order-summary-before-fix"),
            ("After fix", "order-summary"),
        ]:
            path = reverse(name)
            response = client.get(path)
            if response.status_code != 200:
                raise CommandError(f"{path} returned {response.status_code}")
            silk_request = Request.objects.filter(path=path).order_by("-start_time").first()
            rows.append((label, path, response.json()["order_count"], silk_request))

        before = rows[0][3]
        # Group statements by shape so "WHERE id = 16" and "WHERE id = 17" count together.
        repeated = Counter(
            re.sub(r"\b\d+\b", "?", q.query) for q in before.queries.all()
        ).most_common(2)

        lines = [
            "# Section 1 profiler output (django-silk)",
            "",
            "Generated by `python manage.py profile_summary` against the seeded `demo` user.",
            "Numbers are read back from silk's `Request` / `SQLQuery` tables; the same",
            "requests are visible in the silk UI at `/silk/`.",
            "",
            "| Endpoint | Path | Orders | SQL queries | Time in SQL (ms) | Total time (ms) |",
            "|---|---|---:|---:|---:|---:|",
        ]
        for label, path, order_count, req in rows:
            sql_ms = sum(q.time_taken or 0 for q in req.queries.all())
            lines.append(
                f"| {label} | `{path}` | {order_count} | {req.num_sql_queries} "
                f"| {sql_ms:.0f} | {req.time_taken:.0f} |"
            )
        lines += ["", "Most repeated statements before the fix:", ""]
        for sql, count in repeated:
            lines += [f"- {count} x", "", "  ```sql", f"  {sql}", "  ```", ""]
        lines += ["Queries after the fix (the first two are the session and user lookups):", ""]
        for q in rows[1][3].queries.order_by("start_time"):
            sql = re.sub(r'("session_key" = )\w+', r"\1<redacted>", q.query)
            lines += ["  ```sql", f"  {sql}", "  ```", ""]

        REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
        REPORT_PATH.write_text("\n".join(lines))
        for label, path, order_count, req in rows:
            self.stdout.write(
                f"{label:<11} {path:<32} queries={req.num_sql_queries:<5} "
                f"time={req.time_taken:.0f}ms"
            )
        self.stdout.write(self.style.SUCCESS(f"Report written to {REPORT_PATH}"))
